    WHERE a.autor <> b.autor
),
l_pilipczuka AS (
    SELECT wspolautor autor_p, LEVEL - 1 liczba
    FROM wspolautorstwo
    START WITH wspolautor = 'Pilipczuk Mi'
    CONNECT BY NOCYCLE PRIOR wspolautor = autor
)
SELECT a.id, MIN(p.liczba) liczba_pil
FROM Autor a
LEFT JOIN l_pilipczuka p ON a.id = p.autor_p
GROUP BY a.id
ORDER BY liczba_pil;

